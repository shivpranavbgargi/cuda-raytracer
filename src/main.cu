void gen_scene(int W, int H) {
  sphere *dScene;
  cudaMalloc(&dScene, sizeof(hScene));
  cudaMemcpy(dScene, &hScene, sizeof(hScene), cudaMemcpyHostToDevice);

  int *hPpm, *dPpm;
  hPpm = (int *)malloc(NUM_SUBPIX * H * W * sizeof(int));
  cudaMalloc(&dPpm, NUM_SUBPIX * H * W * sizeof(int));

  const int TX = 8;
  const int TY = 32;
  dim3 block(TX, TY, 1);
  dim3 grid((W + TX - 1) / TX, (H + TY - 1) / TY, 1);

#ifdef PERF
  // Warm up runs (maybe too many iters)
  for (int i = 0; i < 10; i++) {
    gen_scene_kernel<<<grid, block>>>(W, H, dScene, dPpm);
  }
  cudaDeviceSynchronize();

  const unsigned iters = 100;
  float milliseconds = 0;
  cudaEvent_t start, stop;
  cudaEventCreate(&start);
  cudaEventCreate(&stop);
  cudaEventRecord(start, 0);
  for (int i = 0; i < iters; i++) {
    gen_scene_kernel<<<grid, block>>>(W, H, dScene, dPpm);
  }
  cudaEventRecord(stop, 0);
  cudaEventSynchronize(stop);
  cudaEventElapsedTime(&milliseconds, start, stop);
  printf("Kernel Execution Time (Avg over %d iterations): %f ms\n", iters,
         milliseconds / iters);
  cudaEventDestroy(start);
  cudaEventDestroy(stop);
#endif

  gen_scene_kernel<<<grid, block>>>(W, H, dScene, dPpm);
  cudaMemcpy(hPpm, dPpm, NUM_SUBPIX * H * W * sizeof(int),
             cudaMemcpyDeviceToHost); // this takes care of sync, no need of CDS

  unsigned char *hPpmChar =
      (unsigned char *)malloc(NUM_SUBPIX * H * W * sizeof(unsigned char));

  char filePath[255];
  snprintf(filePath, sizeof(filePath), "%s/gpu_image.ppm",
           std::getenv("OUTDIR"));
  FILE *f = fopen(filePath, "wb");
  fprintf(f, "P6\n%d %d\n255\n", W, H);
  for (int i = 0; i < (W * H); i++) {
    unsigned int px = hPpm[i];
    hPpmChar[3 * i] = (unsigned char)(px & 0xFF);
    hPpmChar[3 * i + 1] = (unsigned char)((px >> 8) & 0xFF);
    hPpmChar[3 * i + 2] = (unsigned char)((px >> 16) & 0xFF);
  }
  fwrite(hPpmChar, 1, 3 * W * H * sizeof(unsigned char), f);
  fclose(f);
  printf("Wrote gpu_image.ppm (%dx%d)\n", W, H);
}

int main(int argc, char **argv) {
  if (argc != 3) {
    std::cout << "Usage: " << argv[0] << " <width> <height>" << endl;
    std::cout << "Example: " << argv[0] << " 1920 1080" << endl;
    return 1;
  }
  const int W = atoi(argv[1]), H = atoi(argv[2]);
  gen_scene(W, H);
  return 0;
}
